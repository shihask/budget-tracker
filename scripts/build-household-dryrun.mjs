// Builds supabase/preflight/household_dryrun.sql: the Household migration plus
// its security suite in ONE transaction that ends in ROLLBACK, so both can be
// rehearsed against the real database without keeping anything.
//
//   node scripts/build-household-dryrun.mjs
//
// Generated from the two source files so it can never drift from them: edit the
// migration or supabase/tests/household.sql, then re-run this.

import { readFileSync, writeFileSync } from 'node:fs'

const MIGRATION = 'supabase/migrations/20261027000001_household.sql'
const SUITE = 'supabase/tests/household.sql'
const OUT = 'supabase/preflight/household_dryrun.sql'

function body(path, open, close) {
  const lines = readFileSync(path, 'utf8').replace(/\r\n/g, '\n').split('\n')
  const first = lines.findIndex(l => l.trim() === open)
  const last = lines.findLastIndex(l => l.trim() === close)
  if (first < 0 || last <= first) throw new Error(`${path}: expected a "${open}" … "${close}" block`)
  return lines.slice(first + 1, last).join('\n')
}

const migration = body(MIGRATION, 'BEGIN;', 'COMMIT;')
// The suite's own success line is dropped; the dry run prints its own after ROLLBACK.
const suite = body(SUITE, 'BEGIN;', 'ROLLBACK;').replace(/^SELECT 'HOUSEHOLD SQL CHECKS PASSED';\s*$/m, '')

const sql = `-- GENERATED by scripts/build-household-dryrun.mjs — do not edit by hand.
--
-- Household DRY RUN: applies ${MIGRATION}
-- and runs ${SUITE} inside ONE transaction, then ROLLS BACK.
-- Nothing is kept: no table, function, policy, grant, test user or row survives.
--
-- Paste the whole file into the Supabase SQL editor and run it once.
--   * Success: the only result is "DRY RUN PASSED — nothing was kept".
--   * Any failed check or SQL error aborts the transaction (nothing is kept either
--     way) and the editor shows the error — send it back for review.
--
-- While it runs (a few seconds) the new FK to auth.users holds a lock that makes
-- sign-ups and sign-ins wait. Run it at a quiet time. Existing data is not read
-- except the catalog checks; existing objects are not modified.

BEGIN;

-- ════════════════════════ migration ════════════════════════
${migration}

-- ════════════════════════ security suite ════════════════════════
${suite}

ROLLBACK;

-- Reached only if every statement above succeeded.
SELECT CASE WHEN to_regclass('public.households') IS NULL
            THEN 'DRY RUN PASSED — nothing was kept'
            ELSE 'WARNING: public.households exists — the migration was already applied before this run'
       END AS result;
`

writeFileSync(OUT, sql)
console.log(`wrote ${OUT} (${sql.split('\n').length} lines)`)
